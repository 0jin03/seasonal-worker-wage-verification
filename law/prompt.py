def build_user_message(
    rule_id: str,
    status: str,
    reason: str,
    comparisons: dict | None,
    evidence: dict,
    누락정보: list[str] | None = None,
) -> str:
    """LLM 입력 메시지를 만든다."""
    payload = {
        "rule_id": rule_id,
        "검사내용": evidence["검사내용"],
        "성격": evidence["성격"],
        "판정결과": status,
        "판정사유": reason,
        "비교값": comparisons or {},
        "설명방향": evidence["설명방향"],
        "근거조항": evidence["근거조항"],
        "참고조항": evidence["참고조항"],
        "조건부조항": evidence["조건부조항"],
        "계약서근거": evidence["계약서근거"],
        "참고자료": evidence["참고자료"],
        "금지표현": evidence["금지표현"],
        "검토필요": evidence["검토필요"],
        "누락정보": 누락정보 or [],
        "질문생성지침": QUESTION_POLICY.get(status, QUESTION_POLICY["REVIEW"]),
    }
    return (
        "다음 판정 결과를 설명해라.\n\n```json\n"
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + "\n```"
    )
