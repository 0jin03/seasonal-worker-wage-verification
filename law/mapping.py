# --- 조회 도우미 -------------------------------------------------------

def spec(rule_id: str) -> RuleSpec:
    return RULES[rule_id.upper()]


def laws_for(rule_id: str, include_conditional: bool = True) -> list[Law]:
    items = spec(rule_id).법령
    return [l for l in items if include_conditional or l.역할 != "conditional"]


def clauses_for(rule_id: str) -> list[ContractClause]:
    return list(spec(rule_id).계약서)


def references_for(rule_id: str) -> list[Reference]:
    return list(spec(rule_id).참고자료)
