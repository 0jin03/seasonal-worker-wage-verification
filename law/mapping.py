"""R00~R11 검증 규칙과 근거 자료의 매핑.

설계 원칙 — 모든 Rule이 법 위반을 판단하는 것이 아니다.
    법적기준   법령이 직접 규율하는 의무. 위반 가능성을 말할 수 있다.
    문서정합성  문서 간 값이 다른지 확인한다. 차이 자체는 위반이 아니다.
    산술검산   명세서 내부 계산이 맞는지 확인한다. 법령이 산식을 규정하지 않는다.
    시스템규칙  법적 근거 없이 시스템이 자료를 연결하기 위해 두는 규칙.

이 구분이 프롬프트의 설명 수위를 직접 결정한다. 근거 조항이 붙어 있다는
이유만으로 "법 위반"이라고 설명하면 안 되는 규칙이 절반 이상이다.
"""

from __future__ import annotations

from dataclasses import dataclass, field


# --- 근거 종류 ---------------------------------------------------------

@dataclass(frozen=True)
class Law:
    """법령 조항. 조·항·호 중 가장 좁은 단위까지 지정한다."""

    법령명: str
    조문번호: str
    조문가지번호: str | None = None
    항번호: str | None = None
    호번호: str | None = None
    역할: str = "primary"       # primary | supporting | conditional
    사유: str = ""
    적용조건: str = ""          # 역할이 conditional 일 때 언제 적용되는지


@dataclass(frozen=True)
class ContractClause:
    """표준 계절근로계약서 조항. contract.CLAUSES 의 키를 쓴다."""

    key: str
    역할: str = "primary"
    사유: str = ""


@dataclass(frozen=True)
class Reference:
    """법령이 아닌 공식 자료(고용노동부 자료, 고시, 외부 데이터)."""

    발행처: str
    명칭: str
    사유: str
    역할: str = "supporting"
    식별자: str | None = None
    주의: str = ""
    # law/notice.py 가 수집한 자료로 채울 항목의 키. 연도마다 값이 바뀌는 고시용이다.
    # 여기에 값을 적어 두면 근거를 만들 때 실제 수집값으로 대체된다.
    수집키: str | None = None


@dataclass(frozen=True)
class RuleSpec:
    검사내용: str
    성격: str                                    # 법적기준 | 문서정합성 | 산술검산 | 시스템규칙
    설명방향: str
    법령: tuple[Law, ...] = ()
    계약서: tuple[ContractClause, ...] = ()
    참고자료: tuple[Reference, ...] = ()
    금지표현: tuple[str, ...] = ()               # LLM이 하면 안 되는 설명
    검토필요: str = ""


def _명세서(호: str, 사유: str, 역할: str = "primary") -> Law:
    """근로기준법 시행령 제27조의2 제1항의 특정 호."""
    return Law("근로기준법 시행령", "27", "2", "1", 호, 역할, 사유)


